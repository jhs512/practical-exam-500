def cases(area, topic, entries, scenarios):
    out = []
    for cid, name, definition, label in entries:
        if cid not in scenarios:
            continue
        stem, reason = scenarios[cid]
        siblings = pick([e for e in entries if e[0] != cid], f"release500-{cid}", 9)
        out.append(make_question(
            id=f"release500-{area}-{cid}", area=area, label=label, difficulty=2,
            topic=topic, tags=[topic, name], stem=stem,
            answer=(name, reason),
            distractors=[(other, f"{other}: {explanation} 이 상황에서 결정적인 단서는 다음과 같다. {reason}")
                         for _, other, explanation, _ in siblings],
            ask=f"상황에서 요구하는 판단 기준을 구분한다. {reason}",
            solve=[reason] + ([definition] if definition != reason else []) + [
                f"비교: {other}\n{explanation}\n이 사례에서 적용할 판단 기준: {reason}"
                for _, other, explanation, _ in siblings[:2]],
            tip=definition, family=f"release500-{area}",
        ))
    return out


def generate():
    req = [(cid, name, expl, label) for cid, name, _, expl, label in KNOWLEDGE["01"]]
    ui = [(cid, name, expl, label) for cid, name, _, expl, label in KNOWLEDGE["06"]]
    packaging = [(cid, name, why, 2) for cid, name, _, why in PACKAGING]
    return (cases("01", "요구사항 분석과 모델링", req, REQUIREMENTS)
            + cases("06", "사용자 인터페이스 판단", ui, UI_CASES)
            + cases("12", "배포와 패키징", packaging,
                    {cid: (stem, why) for cid, _, stem, why in PACKAGING}))
