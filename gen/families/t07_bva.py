def make_strict_q(n, case, kind):
    name, unit, a, b, desc = case
    lo, hi = a + 1, b - 1
    vals = [lo - 1, lo, hi, hi + 1] if kind == 2 else [lo - 1, lo, lo + 1, hi - 1, hi, hi + 1]
    wrong = [
        (fmt(two(a, b) if kind == 2 else three(a, b)), f"{a}와 {b}를 포함 경계로 착각했다. 이 명세는 초과·미만이므로 유효 정수 범위가 [{lo}, {hi}]이다."),
        (fmt([a, lo, hi, b]), f"무효인 {a}, {b}와 유효 경계 {lo}, {hi}만 골랐다. 경계 바깥 값은 있으나 이웃 값 구성이 2-value·3-value 어느 규칙과도 맞지 않는다."),
        (fmt([lo, hi]), "유효 경계값만 골랐다. 무효 쪽 바깥 값이 빠져 있다."),
        (fmt([lo - 1, hi + 1]), "바깥 값만 골랐다. 유효 경계 자체를 확인하는 값이 빠졌다."),
        (fmt([lo, lo + 1, hi - 1, hi]), "유효 영역 안쪽 값만 골라 무효 경계가 없다."),
        (fmt([lo - 1, lo, lo + 1, hi, hi + 1]) if kind == 3 else fmt([lo - 1, lo, lo + 1, hi + 1]),
         "상한 쪽 구성을 빠뜨리거나 바꿨다. 하한과 상한은 같은 규칙으로 대칭 적용해야 한다."),
        (fmt([lo - 2, lo - 1, lo, hi, hi + 1, hi + 2]), "경계에서 두 칸씩 바깥으로 넓혔다."),
        (fmt([lo, lo + 1, lo + 2, hi - 2, hi - 1, hi]), "경계 안쪽으로만 세 개씩 골랐다."),
        (fmt([a, a + 1, b - 1, b]), f"무효 경계와 유효 경계를 한 칸씩 어긋나게 골랐다. 유효 시작은 {lo}, 끝은 {hi}다."),
        (fmt([lo - 1, lo + 1, hi - 1, hi + 1]), "유효 경계 자체를 빼고 이웃 값만 골랐다."),
        (fmt([lo - 1, lo, hi]), "상한 바깥 값이 빠졌다. 상한 초과 처리를 확인하지 못한다."),
        (fmt([lo, hi, hi + 1]), "하한 바깥 값이 빠졌다. 하한 미만 처리를 확인하지 못한다."),
    ]
    wrong = [w for w in wrong if w[0] != fmt(vals)]
    if kind == 2:
        line = f"2-value: {fmt(vals)} (바깥 {lo - 1}, 유효 {lo}, 유효 {hi}, 바깥 {hi + 1})."
    else:
        line = f"3-value: 하한에서 {fmt([lo - 1, lo, lo + 1])}, 상한에서 {fmt([hi - 1, hi, hi + 1])}."
    return q(
        f"t07-bva-{n:02d}", TOPIC,
        f"{desc}를 `{name} > {a}` 그리고 `{name} < {b}`로 명세했다(정수 입력, 단위 {unit}). {'경계 바깥 값만 곁들이는 2-value' if kind == 2 else '경계 양쪽 이웃을 모두 쓰는 3-value'} 경계값 분석으로 고를 시험값은?",
        (fmt(vals), f"초과·미만 조건에서 유효 정수 범위는 [{lo}, {hi}]다. 이 경계({lo}, {hi})에 {kind}-value 규칙을 적용했다."),
        wrong,
        f"초과/미만으로 표현된 명세를 유효 정수 범위로 바꾼 뒤 {kind}-value 경계값을 고르는 문제다.",
        [f"`> {a}`와 `< {b}`를 정수 범위로 바꾸면 {lo} 이상 {hi} 이하다. 경계값 분석의 기준은 부등호에 적힌 수({a}, {b})가 아니라 실제로 유효한 첫 값과 마지막 값({lo}, {hi})이다.",
         line,
         f"여기서 {a}와 {b}는 이미 무효값이므로 바깥 값으로 {lo - 1}={a}, {hi + 1}={b}가 쓰인다."],
        "부등호 명세는 먼저 유효 정수 범위(초과는 +1, 미만은 -1)로 환산하고, 그 범위의 경계를 기준으로 값을 고른다.",
        3, tags=["경계값 분석", "초과·미만"])


