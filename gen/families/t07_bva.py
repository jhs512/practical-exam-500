def make_defect_q(n, case, side):
    name, unit, a, b, desc = case
    if side == "lo":
        code = f"def accept(x):\n    return {a} < x <= {b}"
        reveal = a
        others = [b + 1, a - 1, a + 1, (a + b) // 2, b, a + 2, b - 1]
        why = f"구현은 `{a} < x`라서 x={a}를 거절하지만 명세는 {a}를 허용한다. 두 판정이 갈리는 값은 x={a} 하나뿐이다."
    else:
        code = f"def accept(x):\n    return {a} <= x < {b}"
        reveal = b
        others = [a - 1, b + 1, b - 1, (a + b) // 2, a, b - 2, a + 1]
        why = f"구현은 `x < {b}`라서 x={b}를 거절하지만 명세는 {b}를 허용한다. 두 판정이 갈리는 값은 x={b} 하나뿐이다."
    wrong = [(str(v), f"x={v}에서는 명세와 구현의 판정이 같으므로 결함이 드러나지 않는다.") for v in others]
