TOPIC = "동등 분할"

# name: (valid classes, invalid classes)
PARAMS = {
    "나이": (["미성년 0~17", "성인 18~64", "고령 65~120"], ["0 미만", "120 초과"]),
    "수량": (["1~9", "10~99"], ["0 이하", "100 이상"]),
    "결제 수단": (["카드", "계좌이체", "포인트"], ["지원하지 않는 수단"]),
    "회원 등급": (["일반", "우수", "VIP", "직원"], ["등급 코드 없음"]),
    "쿠폰 코드": (["형식 맞는 유효 쿠폰", "쿠폰 미입력"], ["형식 틀린 코드", "만료된 코드"]),
    "배송 지역": (["수도권", "지방", "도서산간", "해외"], []),
    "비밀번호 길이": (["8~16자"], ["8자 미만", "16자 초과"]),
    "약관 동의": (["동의함"], ["동의 안 함"]),
    "점수": (["0~59", "60~69", "70~79", "80~89", "90~100"], ["0 미만", "100 초과"]),
    "메모": (["빈 메모", "1~200자"], ["200자 초과"]),
    "수신 방식": (["이메일", "문자", "앱 알림"], []),
    "첨부 파일 수": (["0개", "1~5개"], ["6개 이상"]),
}


def mistakes(vs, ws, total_valid_prod):
    max_v, sum_v, sum_w = max(vs), sum(vs), sum(ws)
    right = max_v + sum_w
    return right, [
        (str(sum_v + sum_w), "모든 클래스를 각각 별도 케이스로 만들었다. 서로 다른 변수의 유효 클래스는 한 케이스에 함께 담을 수 있다."),
        (str(total_valid_prod + sum_w), "유효 클래스의 모든 조합을 만들었다. 동등 분할은 클래스당 대표값 한 번씩만 커버하면 되므로 곱이 아니다."),
        (str(max_v + max(ws) if ws else max_v), "무효 클래스를 가장 큰 변수 하나만 센 값이다. 무효 클래스는 서로 마스킹되지 않도록 각각 별도 케이스에 둔다."),
        (str(max_v), "유효 케이스만 센 값이다. 무효 클래스는 한 번에 하나씩 따로 확인해야 하므로 추가된다."),
        (str(sum_w + 1), "유효 클래스를 모두 정상 케이스 1개에 담을 수 있다고 보았다. 변수별 유효 클래스가 여럿이면 그 최대 개수만큼 케이스가 필요하다."),
        (str(sum_v), "유효 클래스 개수의 합만 센 값이다. 무효 클래스가 빠져 있고 유효 클래스는 변수 간에 겹쳐 담을 수 있다."),
        (str(sum(vs) * 2 + sum_w), "유효 클래스마다 두 케이스를 쓴 값이다. 클래스당 대표값 하나면 충분하다."),
        (str(max_v * (sum_w or 1)), "유효 최대 개수와 무효 개수를 곱했다. 무효 클래스는 곱이 아니라 각각 하나씩 더해진다."),
        (str(len(vs) + sum_w + max_v), "변수 개수를 추가로 더했다. 변수 개수는 케이스 수와 직접 관계가 없다."),
    ]


def single(n, name, extra=None):
    vs, ws = PARAMS[name]
    right = len(vs) + len(ws)
    wrong = [
        (str(len(vs)), "유효 클래스만 센 값이다. 무효 클래스도 각각 대표값을 하나씩 시험해야 한다."),
        (str(len(vs) * len(ws) if ws else len(vs) * 2), "유효와 무효 개수를 곱했다. 변수가 하나뿐이므로 클래스당 케이스 하나면 된다."),
        (str(len(ws)), "무효 클래스만 센 값이다. 유효 클래스도 대표값을 확인해야 한다."),
        (str(right * 2), "클래스마다 경계값 2개를 쓴 값이다. 동등 분할은 클래스당 대표값 하나가 기본이다."),
    ]
    stem = (f"{name} 입력의 명세를 분석했더니 유효 클래스가 {len(vs)}개({' / '.join(vs)}), "
            f"무효 클래스가 {len(ws)}개({' / '.join(ws) if ws else '없음'})로 나뉜다. 다른 입력은 고려하지 않고, "
            f"각 클래스에서 대표값 하나씩을 골라 모든 클래스를 한 번씩 커버하려면 최소 몇 개의 시험 케이스가 필요한가?")
    return q(f"t07-ep-{n:02d}", TOPIC, stem,
             (str(right), f"변수가 하나라 한 케이스는 한 클래스만 지나간다. {len(vs)} + {len(ws)} = {right}개다."),
             wrong, "하나의 입력 변수에서 모든 동등 클래스를 한 번씩 커버하는 최소 케이스 수를 계산한다.",
             [f"동등 분할은 입력을 같은 방식으로 처리되는 클래스로 나누고 클래스마다 대표값 하나를 시험한다. 유효 {len(vs)}개, 무효 {len(ws)}개다.",
              f"입력 변수가 하나이므로 한 케이스는 단 하나의 클래스만 대표한다. 따라서 필요한 최소 케이스 수는 전체 클래스 수 {len(vs)} + {len(ws)} = {right}이다.",
              "대표값이 하나뿐이므로 클래스 내부에서 경계 오류까지 잡지는 못한다. 그것은 경계값 분석이 보완한다."],
             "변수가 하나면 클래스 수 = 최소 케이스 수. 변수가 여럿이면 유효는 겹쳐 담고 무효는 하나씩 따로 담는다.",
             1, pad=right)


def multi(n, names, diff):
    vs = [len(PARAMS[x][0]) for x in names]
    ws = [len(PARAMS[x][1]) for x in names]
    prod = 1
    for v in vs:
        prod *= v
    right, wrong = mistakes(vs, ws, prod)
    rows = [[x, ", ".join(PARAMS[x][0]), ", ".join(PARAMS[x][1]) or "없음"] for x in names]
    stem = ("다음 표는 한 화면의 입력 변수와 동등 분할 결과다. 모든 클래스를 한 번씩 커버하되 "
            "유효 클래스는 서로 다른 변수끼리 한 케이스에 함께 담을 수 있고, 무효 클래스는 결함이 가려지지 않도록 "
            "한 케이스에 하나씩만 넣는다. 필요한 최소 시험 케이스 수는?")
    return q(f"t07-ep-{n:02d}", TOPIC, stem,
             (str(right), f"유효 케이스는 변수별 유효 클래스 수의 최댓값 {max(vs)}개, 무효 케이스는 무효 클래스 총수 {sum(ws)}개이다."),
             wrong, "여러 변수의 동등 클래스를 모두 커버하는 최소 케이스 수를 구한다.",
             [f"유효 클래스는 케이스 하나에 변수별로 하나씩 담을 수 있다. 변수별 유효 클래스 수는 {vs}이므로 가장 큰 변수 하나에 맞춰 {max(vs)}개의 유효 케이스면 모든 유효 클래스를 덮는다.",
              f"무효 클래스는 한 케이스에 하나씩만 넣어야 한다. 무효 클래스 수는 {ws}이고 합은 {sum(ws)}이다. 이 케이스에서 다른 변수는 유효 대표값으로 둔다.",
              f"합계: {max(vs)} + {sum(ws)} = {right}. 유효 조합 전체({prod})나 클래스 총수({sum(vs) + sum(ws)})를 세는 것은 과다하다."],
             "최소 케이스 = max(변수별 유효 클래스 수) + Σ(무효 클래스 수). 유효는 겹치고, 무효는 겹치지 않는다.",
             diff, tables=[{"caption": "입력 변수별 동등 클래스", "columns": ["변수", "유효 클래스", "무효 클래스"], "rows": rows}],
             pad=right)


def generate():
    out = [single(1, "나이"), single(2, "비밀번호 길이"), single(3, "점수")]
    sets = [(["나이", "결제 수단", "약관 동의"], 2),
            (["수량", "회원 등급", "쿠폰 코드"], 2),
            (["배송 지역", "비밀번호 길이", "메모", "수신 방식"], 3),
            (["점수", "첨부 파일 수", "약관 동의", "결제 수단"], 3),
            (["수량", "회원 등급", "첨부 파일 수", "쿠폰 코드", "수신 방식"], 3)]
    for i, (names, d) in enumerate(sets, 4):
        out.append(multi(i, names, d))
    return out
